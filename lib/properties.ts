export function formatPrice(price: number, currency: "MAD" | "EUR" = "MAD"): string {
  return `${new Intl.NumberFormat("fr-FR").format(price)} ${currency}`;
}

export function getCities() {
  const cities = Array.from(new Set(properties.map((property) => property.location.city)));
  return cities.map((city) => ({
    name: city,
    count: properties.filter((property) => property.location.city === city).length,
  }));
}

